import {readFile,writeFile} from 'node:fs/promises';
import {join} from 'node:path';
const root=new URL('../dist/',import.meta.url);
let html=await readFile(new URL('index.html',root),'utf8');
const script=html.match(/<script type="module" crossorigin src="([^"]+)"><\/script>/);
const style=html.match(/<link rel="stylesheet" crossorigin href="([^"]+)">/);
if(!script||!style)throw new Error('Expected one Vite JS and CSS bundle');
const js=await readFile(new URL(script[1].replace(/^\//,''),root),'utf8');
const css=await readFile(new URL(style[1].replace(/^\//,''),root),'utf8');
html=html.replace(script[0],()=>`<script type="module">${js.replace(/<\/script/gi,'<\\/script')}</script>`);
html=html.replace(style[0],()=>`<style>${css}</style>`);
const output=process.argv[2]||join(new URL(root).pathname,'qihuang-demo.html');
await writeFile(output,html);
console.log(`Exported standalone demo: ${output}`);
